/**
 * Validates whether a normalized guess is accepted for a puzzle of `targetLength`.
 * Returns `{ valid, isBeerTerm }`.
 */
export function validateGuessWord(
  normalizedGuess: string,
  targetLength: number,
): { valid: boolean; isBeerTerm: boolean } {
  if (splitGraphemes(normalizedGuess).length !== targetLength) {
    return { valid: false, isBeerTerm: false };
  }
  return {
    valid: true,
    isBeerTerm: BEER_TERM_SET.has(normalizedGuess),
  };
}

/**
 * Looks up metadata for a given canonical daily puzzle word.
 */
export function getBeerMetadata(word: string): BeerMetadata | undefined {
  const normalized = normalizeBeerString(word);
  return DAILY_BEER_SOLUTIONS.find((b) => b.word === normalized);
}
